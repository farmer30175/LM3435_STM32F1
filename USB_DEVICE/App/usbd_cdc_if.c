/* VCP command queue. Characters are stored by the USB IRQ; the main loop
   (main.c -> VCP_Process -> VCP_QueuePop) pulls whole lines, so no blocking
   I2C call ever runs in an ISR.
   A plain single buffer cannot be used: several commands typed faster than the
   main loop can consume them overwrite each other ("PINGPINGPING"). */
#define VCP_Q_DEPTH  4U

static char            vcp_q_buf[VCP_Q_DEPTH][VCP_CMD_BUFFER_SIZE];
static volatile uint8_t vcp_q_head = 0U;    /* written by the USB IRQ  */
static volatile uint8_t vcp_q_tail = 0U;    /* written by the main loop */
static volatile uint8_t vcp_rx_index = 0U;  /* chars of the line being typed */
static volatile uint32_t vcp_rx_tick = 0U;

/* Seal the line currently being typed as one complete command.
   Call with interrupts disabled, or from the USB IRQ. */
static void VCP_Q_Push(void)
{
    uint8_t next;

    if (vcp_rx_index == 0U)
    {
        return;                        /* nothing pending */
    }

    next = (uint8_t)((vcp_q_head + 1U) % VCP_Q_DEPTH);
    if (next == vcp_q_tail)
    {
        return;                        /* queue full: drop this command */
    }

    vcp_q_buf[vcp_q_head][vcp_rx_index] = '\0';
    vcp_q_head = next;
    vcp_rx_index = 0U;
}

uint8_t VCP_QueuePop(char *dst)
{
    uint8_t  got = 0U;
    uint32_t now = HAL_GetTick();

    __disable_irq();

    /* Terminals that send no line ending at all: seal the line after a short
       pause in typing, so "LM3435 10" still arrives as one command. */
    if ((vcp_rx_index > 0U) && ((now - vcp_rx_tick) >= 500U))
    {
        VCP_Q_Push();
    }

    if (vcp_q_head != vcp_q_tail)
    {
        (void)strcpy(dst, vcp_q_buf[vcp_q_tail]);
        vcp_q_tail = (uint8_t)((vcp_q_tail + 1U) % VCP_Q_DEPTH);
        got = 1U;
    }

    __enable_irq();
    return got;
}

